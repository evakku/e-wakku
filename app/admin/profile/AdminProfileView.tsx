"use client";

import { useState, useEffect, useTransition } from "react";
import {
  User,
  Mail,
  Lock,
  KeyRound,
  Eye,
  EyeOff,
  Check,
  X,
  AlertCircle,
  ShieldCheck,
  ShieldAlert,
  Copy,
  CheckCircle2,
  UserPlus,
  UserMinus,
  AlertTriangle,
  Sparkles,
  Loader2,
} from "lucide-react";
import {
  updateAdminDisplayName,
  changeAdminPassword,
  createAdministrator,
  removeAdministrator,
  listAdministrators,
  type AdminUserItem,
  type AdminProfileData,
} from "./actions";
import {
  getPasswordRuleChecklist,
  generateSecureAdminPassword,
  formatCredentialSharingMessage,
  validateAdminPassword,
} from "@/lib/validation/password";
import { useAdminProfile } from "@/components/admin/AdminProfileContext";
import { createClient } from "@/lib/supabase/client";

interface AdminProfileViewProps {
  initialProfile: AdminProfileData;
  initialAdmins: AdminUserItem[];
}

export default function AdminProfileView({
  initialProfile,
  initialAdmins,
}: AdminProfileViewProps) {
  const { setAdminName: setContextAdminName } = useAdminProfile();

  // Synchronize top navigation immediately with authoritative profile name
  useEffect(() => {
    if (initialProfile.name && initialProfile.name.trim()) {
      setContextAdminName(initialProfile.name.trim());
    }
  }, [initialProfile.name, setContextAdminName]);

  // Profile Section State
  const [displayName, setDisplayName] = useState(initialProfile.name);
  const [isEditingName, setIsEditingName] = useState(false);
  const [nameInput, setNameInput] = useState(initialProfile.name);
  const [profileMessage, setProfileMessage] = useState<{ type: "success" | "error"; text: string } | null>(null);
  const [isUpdatingName, startNameTransition] = useTransition();

  // Change Password Section State
  const [currentPassword, setCurrentPassword] = useState("");
  const [newPassword, setNewPassword] = useState("");
  const [confirmPassword, setConfirmPassword] = useState("");
  const [showCurrentPassword, setShowCurrentPassword] = useState(false);
  const [showNewPassword, setShowNewPassword] = useState(false);
  const [showConfirmPassword, setShowConfirmPassword] = useState(false);
  const [passwordMessage, setPasswordMessage] = useState<{ type: "success" | "error"; text: string } | null>(null);
  const [isChangingPassword, startPasswordTransition] = useTransition();

  // Administrators List State
  const [adminsList, setAdminsList] = useState<AdminUserItem[]>(initialAdmins);

  // Add Admin Modal State
  const [isAddModalOpen, setIsAddModalOpen] = useState(false);
  const [newAdminName, setNewAdminName] = useState("");
  const [newAdminEmail, setNewAdminEmail] = useState("");
  const [newAdminPassword, setNewAdminPassword] = useState("");
  const [newAdminConfirmPassword, setNewAdminConfirmPassword] = useState("");
  const [showNewAdminPassword, setShowNewAdminPassword] = useState(false);
  const [showNewAdminConfirmPassword, setShowNewAdminConfirmPassword] = useState(false);
  const [isAutoGenerated, setIsAutoGenerated] = useState(false);
  const [addAdminError, setAddAdminError] = useState<string | null>(null);

  // Confirmation Dialog State
  const [isConfirmDialogOpen, setIsConfirmDialogOpen] = useState(false);
  const [isCreatingAdmin, startCreateTransition] = useTransition();

  // Credential Sharing Dialog State
  const [createdAdminCredentials, setCreatedAdminCredentials] = useState<{
    name: string;
    email: string;
    password: string;
  } | null>(null);
  const [isCopied, setIsCopied] = useState(false);

  // Remove Admin Dialog State
  const [adminToRemove, setAdminToRemove] = useState<AdminUserItem | null>(null);
  const [isRemoveDialogOpen, setIsRemoveDialogOpen] = useState(false);
  const [removeAdminError, setRemoveAdminError] = useState<string | null>(null);
  const [adminListSuccessMessage, setAdminListSuccessMessage] = useState<string | null>(null);
  const [isRemovingAdmin, startRemoveTransition] = useTransition();

  // ─────────────────────────────────────────────────────────────────────────────
  // 1. Profile Handlers
  // ─────────────────────────────────────────────────────────────────────────────

  const handleSaveName = () => {
    setProfileMessage(null);
    const trimmed = nameInput.trim();

    if (!trimmed) {
      setProfileMessage({ type: "error", text: "Display name cannot be empty." });
      return;
    }

    if (trimmed.length < 2) {
      setProfileMessage({ type: "error", text: "Name must be at least 2 characters long." });
      return;
    }

    startNameTransition(async () => {
      const result = await updateAdminDisplayName(trimmed);
      if (result.success && result.name) {
        setDisplayName(result.name);
        setContextAdminName(result.name);
        setIsEditingName(false);
        setProfileMessage({ type: "success", text: "Display name updated successfully." });

        // Update current admin in the list
        setAdminsList((prev) =>
          prev.map((adm) => (adm.isCurrentAdmin ? { ...adm, name: result.name! } : adm))
        );

        // Synchronize client-side Supabase session cache so all layout and child components reflect the new name
        try {
          const supabase = createClient();
          await supabase.auth.refreshSession();
        } catch {
          // Non-critical session refresh error
        }
      } else {
        setProfileMessage({ type: "error", text: result.error || "Failed to update display name." });
      }
    });
  };

  const handleCancelEditName = () => {
    setNameInput(displayName);
    setIsEditingName(false);
    setProfileMessage(null);
  };

  // ─────────────────────────────────────────────────────────────────────────────
  // 2. Change Password Handlers
  // ─────────────────────────────────────────────────────────────────────────────

  const newPasswordChecklist = getPasswordRuleChecklist(newPassword, {
    name: displayName,
    email: initialProfile.email,
  });

  const isNewPasswordValid =
    newPassword.length >= 8 &&
    newPasswordChecklist.every((c) => c.satisfied) &&
    newPassword === confirmPassword;

  const handleChangePassword = (e: React.FormEvent) => {
    e.preventDefault();
    setPasswordMessage(null);

    if (!currentPassword) {
      setPasswordMessage({ type: "error", text: "Please enter your current password." });
      return;
    }

    if (newPassword !== confirmPassword) {
      setPasswordMessage({ type: "error", text: "New password and confirmation do not match." });
      return;
    }

    const validation = validateAdminPassword(newPassword, {
      name: displayName,
      email: initialProfile.email,
    });

    if (!validation.valid) {
      setPasswordMessage({ type: "error", text: validation.errors[0] });
      return;
    }

    startPasswordTransition(async () => {
      const formData = new FormData();
      formData.append("currentPassword", currentPassword);
      formData.append("newPassword", newPassword);
      formData.append("confirmPassword", confirmPassword);

      const result = await changeAdminPassword(formData);
      if (result.success) {
        setPasswordMessage({
          type: "success",
          text: "Your password has been changed successfully.",
        });
        setCurrentPassword("");
        setNewPassword("");
        setConfirmPassword("");
      } else {
        setPasswordMessage({
          type: "error",
          text: result.error || "Failed to change password. Please verify your current password.",
        });
      }
    });
  };

  // ─────────────────────────────────────────────────────────────────────────────
  // 3. Add Administrator Handlers
  // ─────────────────────────────────────────────────────────────────────────────

  const newAdminChecklist = getPasswordRuleChecklist(newAdminPassword, {
    name: newAdminName,
    email: newAdminEmail,
  });

  const handleGeneratePassword = () => {
    try {
      const generated = generateSecureAdminPassword({
        name: newAdminName,
        email: newAdminEmail,
      });
      setNewAdminPassword(generated);
      setNewAdminConfirmPassword(generated);
      setIsAutoGenerated(true);
      setAddAdminError(null);
    } catch (err: unknown) {
      setAddAdminError(
        err instanceof Error
          ? err.message
          : "Failed to generate password. Please enter one manually."
      );
    }
  };

  const handleOpenConfirmDialog = (e: React.FormEvent) => {
    e.preventDefault();
    setAddAdminError(null);

    const trimmedName = newAdminName.trim();
    const trimmedEmail = newAdminEmail.trim();

    if (!trimmedName || trimmedName.length < 2) {
      setAddAdminError("Please enter a valid administrator name (min 2 characters).");
      return;
    }

    if (!trimmedEmail || !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(trimmedEmail)) {
      setAddAdminError("Please enter a valid email address.");
      return;
    }

    if (newAdminPassword !== newAdminConfirmPassword) {
      setAddAdminError("Passwords do not match.");
      return;
    }

    const validation = validateAdminPassword(newAdminPassword, {
      name: trimmedName,
      email: trimmedEmail,
    });

    if (!validation.valid) {
      setAddAdminError(validation.errors[0]);
      return;
    }

    // Open confirmation dialog without exposing password
    setIsConfirmDialogOpen(true);
  };

  const handleConfirmCreateAdmin = () => {
    startCreateTransition(async () => {
      const result = await createAdministrator({
        name: newAdminName.trim(),
        email: newAdminEmail.trim(),
        password: newAdminPassword,
        confirmPassword: newAdminConfirmPassword,
      });

      if (result.success) {
        setIsConfirmDialogOpen(false);
        setIsAddModalOpen(false);

        // Retain credentials in memory for one-time sharing dialog
        setCreatedAdminCredentials({
          name: newAdminName.trim(),
          email: newAdminEmail.trim(),
          password: newAdminPassword,
        });

        // Add to active table view using authoritative server UUID
        if (result.id) {
          setAdminsList((prev) => [
            ...prev,
            {
              id: result.id!,
              name: newAdminName.trim(),
              email: newAdminEmail.trim(),
              status: "active",
              createdAt: new Date().toISOString(),
              isCurrentAdmin: false,
              isPrimaryAdmin: false,
            },
          ]);
        }

        // Authoritatively refresh the list from the server to guarantee persistence
        try {
          const fresh = await listAdministrators();
          if (fresh.admins) {
            setAdminsList(fresh.admins);
          }
        } catch {
          // Retain optimistic table update
        }

        // Reset creation form state
        setNewAdminName("");
        setNewAdminEmail("");
        setNewAdminPassword("");
        setNewAdminConfirmPassword("");
        setIsAutoGenerated(false);
      } else {
        setIsConfirmDialogOpen(false);
        setAddAdminError(result.error || "Failed to create administrator account.");
      }
    });
  };

  const handleCopyCredentials = async () => {
    if (!createdAdminCredentials) return;

    const message = formatCredentialSharingMessage(
      createdAdminCredentials.name,
      createdAdminCredentials.email,
      createdAdminCredentials.password
    );

    try {
      await navigator.clipboard.writeText(message);
      setIsCopied(true);
      setTimeout(() => setIsCopied(false), 3000);
    } catch {
      alert("Unable to copy to clipboard automatically. Please copy manually.");
    }
  };

  const handleCloseCredentialsDialog = () => {
    // Clear temporary credentials completely from memory
    setCreatedAdminCredentials(null);
    setIsCopied(false);
  };

  // ─────────────────────────────────────────────────────────────────────────────
  // 4. Administrator Removal Handlers
  // ─────────────────────────────────────────────────────────────────────────────

  const handleOpenRemoveDialog = (admin: AdminUserItem) => {
    setRemoveAdminError(null);
    setAdminToRemove(admin);
    setIsRemoveDialogOpen(true);
  };

  const handleCloseRemoveDialog = () => {
    if (isRemovingAdmin) return;
    setIsRemoveDialogOpen(false);
    setAdminToRemove(null);
    setRemoveAdminError(null);
  };

  const handleConfirmRemoveAdmin = () => {
    if (!adminToRemove) return;

    setRemoveAdminError(null);
    startRemoveTransition(async () => {
      const result = await removeAdministrator(adminToRemove.id);

      if (result.success) {
        setAdminsList((prev) => prev.filter((adm) => adm.id !== adminToRemove.id));
        setIsRemoveDialogOpen(false);
        setAdminToRemove(null);
        setAdminListSuccessMessage("Administrator access removed successfully.");
        setTimeout(() => setAdminListSuccessMessage(null), 5000);

        // Authoritatively refresh the administrators list from the server
        try {
          const fresh = await listAdministrators();
          if (fresh.admins) {
            setAdminsList(fresh.admins);
          }
        } catch {
          // Retain state update
        }
      } else {
        setRemoveAdminError(result.error || "Failed to remove administrator.");
      }
    });
  };

  return (
    <div className="flex flex-col gap-8 max-w-5xl animate-fade-in pb-12">
      {/* ── Page Header ────────────────────────────────────────────── */}
      <div>
        <h2 className="font-heading text-2xl font-semibold text-[#0F172A] tracking-tight">
          Admin Profile
        </h2>
        <p className="mt-1 font-sans text-sm text-[#64748B]">
          Manage your administrator profile, password, and authorized administrators.
        </p>
      </div>

      {/* ── Grid: My Profile & Change Password ─────────────────────── */}
      <div className="grid grid-cols-1 lg:grid-cols-2 gap-6 items-start">
        {/* Section A: My Profile */}
        <div className="bg-white rounded-xl border border-[#E2E8F0] shadow-sm p-6 flex flex-col gap-5">
          <div className="flex items-center gap-3 border-b border-[#E2E8F0] pb-4">
            <div className="w-10 h-10 rounded-full bg-emerald-50 border border-emerald-100 flex items-center justify-center text-[#059669]">
              <User size={20} />
            </div>
            <div>
              <h3 className="font-heading text-base font-semibold text-[#0F172A]">
                My Profile
              </h3>
              <p className="text-xs text-[#64748B]">
                Your personal administrator identity and contact details
              </p>
            </div>
          </div>

          {profileMessage && (
            <div
              className={`p-3 rounded-lg text-sm border flex items-center gap-2 ${
                profileMessage.type === "success"
                  ? "bg-emerald-50 text-emerald-800 border-emerald-200"
                  : "bg-red-50 text-red-800 border-red-200"
              }`}
            >
              {profileMessage.type === "success" ? (
                <CheckCircle2 size={16} className="text-emerald-600 shrink-0" />
              ) : (
                <AlertCircle size={16} className="text-red-600 shrink-0" />
              )}
              <span>{profileMessage.text}</span>
            </div>
          )}

          {/* Display Name Field */}
          <div className="flex flex-col gap-1.5">
            <label
              htmlFor="displayNameInput"
              className="font-sans text-xs font-semibold text-[#45464D] uppercase tracking-wider"
            >
              Display Name
            </label>
            {isEditingName ? (
              <div className="flex flex-col gap-3">
                <input
                  id="displayNameInput"
                  type="text"
                  value={nameInput}
                  onChange={(e) => setNameInput(e.target.value)}
                  maxLength={100}
                  disabled={isUpdatingName}
                  className="w-full px-3.5 py-2.5 rounded-lg border border-[#CBD5E1] text-sm text-[#0F172A] focus:outline-none focus:ring-2 focus:ring-[#059669] focus:border-transparent transition-all"
                  placeholder="e.g. Anu Thomas"
                />
                <div className="flex items-center gap-2">
                  <button
                    type="button"
                    onClick={handleSaveName}
                    disabled={isUpdatingName}
                    className="inline-flex items-center justify-center gap-1.5 px-4 py-2 bg-[#059669] hover:bg-[#047857] text-white text-xs font-medium rounded-lg transition-colors shadow-sm disabled:opacity-50 outline-none focus-visible:ring-2 focus-visible:ring-[#059669]"
                  >
                    {isUpdatingName ? (
                      <>
                        <Loader2 size={14} className="animate-spin" />
                        Saving...
                      </>
                    ) : (
                      <>
                        <Check size={14} />
                        Save Changes
                      </>
                    )}
                  </button>
                  <button
                    type="button"
                    onClick={handleCancelEditName}
                    disabled={isUpdatingName}
                    className="px-3.5 py-2 text-xs font-medium text-[#64748B] hover:text-[#0F172A] hover:bg-[#F1F5F9] rounded-lg transition-colors"
                  >
                    Cancel
                  </button>
                </div>
              </div>
            ) : (
              <div className="flex items-center justify-between p-3 rounded-lg bg-[#F8FAFC] border border-[#E2E8F0]">
                <span className="text-sm font-medium text-[#0F172A]">
                  {displayName || <span className="text-[#94A3B8] italic">No name set (Admin)</span>}
                </span>
                <button
                  type="button"
                  onClick={() => {
                    setNameInput(displayName);
                    setIsEditingName(true);
                  }}
                  className="text-xs font-medium text-[#059669] hover:text-[#047857] hover:underline px-2 py-1"
                >
                  Edit Name
                </button>
              </div>
            )}
          </div>

          {/* Email Address Field (Read-only) */}
          <div className="flex flex-col gap-1.5">
            <label
              htmlFor="emailInput"
              className="font-sans text-xs font-semibold text-[#45464D] uppercase tracking-wider"
            >
              Email Address
            </label>
            <div className="flex items-center gap-2.5 px-3.5 py-2.5 rounded-lg bg-[#F1F5F9] border border-[#E2E8F0] text-sm text-[#475569]">
              <Mail size={15} className="text-[#64748B] shrink-0" />
              <span className="truncate">{initialProfile.email}</span>
              <span className="ml-auto text-[11px] font-medium text-[#64748B] bg-white px-2 py-0.5 rounded border border-[#CBD5E1]">
                Read-only
              </span>
            </div>
            <p className="text-[11px] text-[#64748B]">
              Email is managed by Supabase Authentication identity.
            </p>
          </div>
        </div>

        {/* Section B: Change Password */}
        <div className="bg-white rounded-xl border border-[#E2E8F0] shadow-sm p-6 flex flex-col gap-5">
          <div className="flex items-center gap-3 border-b border-[#E2E8F0] pb-4">
            <div className="w-10 h-10 rounded-full bg-emerald-50 border border-emerald-100 flex items-center justify-center text-[#059669]">
              <KeyRound size={20} />
            </div>
            <div>
              <h3 className="font-heading text-base font-semibold text-[#0F172A]">
                Change Password
              </h3>
              <p className="text-xs text-[#64748B]">
                Update your account password with security validation
              </p>
            </div>
          </div>

          {passwordMessage && (
            <div
              className={`p-3 rounded-lg text-sm border flex items-center gap-2 ${
                passwordMessage.type === "success"
                  ? "bg-emerald-50 text-emerald-800 border-emerald-200"
                  : "bg-red-50 text-red-800 border-red-200"
              }`}
            >
              {passwordMessage.type === "success" ? (
                <CheckCircle2 size={16} className="text-emerald-600 shrink-0" />
              ) : (
                <AlertCircle size={16} className="text-red-600 shrink-0" />
              )}
              <span>{passwordMessage.text}</span>
            </div>
          )}

          <form onSubmit={handleChangePassword} className="flex flex-col gap-4">
            {/* Current Password */}
            <div className="flex flex-col gap-1.5">
              <label
                htmlFor="currentPassword"
                className="font-sans text-xs font-semibold text-[#45464D] uppercase tracking-wider"
              >
                Current Password
              </label>
              <div className="relative">
                <input
                  id="currentPassword"
                  type={showCurrentPassword ? "text" : "password"}
                  value={currentPassword}
                  onChange={(e) => setCurrentPassword(e.target.value)}
                  disabled={isChangingPassword}
                  className="w-full pl-3.5 pr-10 py-2.5 rounded-lg border border-[#CBD5E1] text-sm text-[#0F172A] focus:outline-none focus:ring-2 focus:ring-[#059669] focus:border-transparent transition-all"
                  placeholder="Enter current password"
                />
                <button
                  type="button"
                  onClick={() => setShowCurrentPassword((p) => !p)}
                  aria-label={showCurrentPassword ? "Hide password" : "Show password"}
                  className="absolute right-3 top-1/2 -translate-y-1/2 text-[#94A3B8] hover:text-[#475569] p-1"
                >
                  {showCurrentPassword ? <EyeOff size={16} /> : <Eye size={16} />}
                </button>
              </div>
            </div>

            {/* New Password */}
            <div className="flex flex-col gap-1.5">
              <label
                htmlFor="newPassword"
                className="font-sans text-xs font-semibold text-[#45464D] uppercase tracking-wider"
              >
                New Password
              </label>
              <div className="relative">
                <input
                  id="newPassword"
                  type={showNewPassword ? "text" : "password"}
                  value={newPassword}
                  onChange={(e) => setNewPassword(e.target.value)}
                  disabled={isChangingPassword}
                  className="w-full pl-3.5 pr-10 py-2.5 rounded-lg border border-[#CBD5E1] text-sm text-[#0F172A] focus:outline-none focus:ring-2 focus:ring-[#059669] focus:border-transparent transition-all"
                  placeholder="Enter new password"
                />
                <button
                  type="button"
                  onClick={() => setShowNewPassword((p) => !p)}
                  aria-label={showNewPassword ? "Hide password" : "Show password"}
                  className="absolute right-3 top-1/2 -translate-y-1/2 text-[#94A3B8] hover:text-[#475569] p-1"
                >
                  {showNewPassword ? <EyeOff size={16} /> : <Eye size={16} />}
                </button>
              </div>
            </div>

            {/* Confirm New Password */}
            <div className="flex flex-col gap-1.5">
              <label
                htmlFor="confirmPassword"
                className="font-sans text-xs font-semibold text-[#45464D] uppercase tracking-wider"
              >
                Confirm New Password
              </label>
              <div className="relative">
                <input
                  id="confirmPassword"
                  type={showConfirmPassword ? "text" : "password"}
                  value={confirmPassword}
                  onChange={(e) => setConfirmPassword(e.target.value)}
                  disabled={isChangingPassword}
                  className="w-full pl-3.5 pr-10 py-2.5 rounded-lg border border-[#CBD5E1] text-sm text-[#0F172A] focus:outline-none focus:ring-2 focus:ring-[#059669] focus:border-transparent transition-all"
                  placeholder="Re-type new password"
                />
                <button
                  type="button"
                  onClick={() => setShowConfirmPassword((p) => !p)}
                  aria-label={showConfirmPassword ? "Hide password" : "Show password"}
                  className="absolute right-3 top-1/2 -translate-y-1/2 text-[#94A3B8] hover:text-[#475569] p-1"
                >
                  {showConfirmPassword ? <EyeOff size={16} /> : <Eye size={16} />}
                </button>
              </div>
              {confirmPassword && newPassword !== confirmPassword && (
                <span className="text-xs text-red-600 mt-0.5">Passwords do not match.</span>
              )}
            </div>

            {/* Live Password Checklist */}
            <div className="bg-[#F8FAFC] border border-[#E2E8F0] rounded-lg p-3.5 flex flex-col gap-2 mt-1">
              <span className="text-xs font-semibold text-[#475569]">
                Password Requirements:
              </span>
              <ul className="grid grid-cols-1 sm:grid-cols-2 gap-1.5 text-xs">
                {newPasswordChecklist.map((rule) => {
                  let statusColor = "text-[#64748B]";
                  let icon = <span className="w-1.5 h-1.5 rounded-full bg-[#CBD5E1] inline-block shrink-0" />;

                  if (rule.satisfied) {
                    statusColor = "text-emerald-700 font-medium";
                    icon = <Check size={13} className="text-[#059669] shrink-0" />;
                  } else if (rule.isViolation) {
                    statusColor = "text-red-700 font-medium";
                    icon = <X size={13} className="text-red-600 shrink-0" />;
                  }

                  return (
                    <li key={rule.id} className={`flex items-center gap-1.5 ${statusColor}`}>
                      {icon}
                      <span>{rule.label}</span>
                    </li>
                  );
                })}
              </ul>
            </div>

            {/* Submit Button */}
            <button
              type="submit"
              disabled={isChangingPassword || !isNewPasswordValid || !currentPassword}
              className="inline-flex items-center justify-center gap-2 px-4 py-2.5 bg-[#059669] hover:bg-[#047857] text-white text-sm font-medium rounded-lg transition-colors shadow-sm disabled:opacity-50 disabled:cursor-not-allowed outline-none focus-visible:ring-2 focus-visible:ring-[#059669]"
            >
              {isChangingPassword ? (
                <>
                  <Loader2 size={16} className="animate-spin" />
                  Updating Password...
                </>
              ) : (
                <>
                  <Lock size={16} />
                  Change Password
                </>
              )}
            </button>
          </form>
        </div>
      </div>

      {/* ── Section C: Administrators List ─────────────────────────── */}
      <div className="bg-white rounded-xl border border-[#E2E8F0] shadow-sm p-6 flex flex-col gap-6">
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 border-b border-[#E2E8F0] pb-5">
          <div>
            <h3 className="font-heading text-lg font-semibold text-[#0F172A]">
              Administrators
            </h3>
            <p className="mt-1 font-sans text-xs sm:text-sm text-[#64748B]">
              Authorized administrators have full access to manage magazine issues, view analytics, and respond to enquiries.
            </p>
          </div>
          <button
            type="button"
            onClick={() => {
              setAddAdminError(null);
              setIsAddModalOpen(true);
            }}
            className="inline-flex items-center justify-center gap-2 px-4 py-2 bg-[#059669] hover:bg-[#047857] text-white text-sm font-medium rounded-lg transition-colors shadow-sm self-start sm:self-auto shrink-0 outline-none focus-visible:ring-2 focus-visible:ring-[#059669]"
          >
            <UserPlus size={16} />
            Add New Admin
          </button>
        </div>

        {adminListSuccessMessage && (
          <div className="p-3.5 bg-emerald-50 text-emerald-800 border border-emerald-200 text-xs sm:text-sm rounded-lg flex items-center justify-between gap-2 animate-fade-in">
            <div className="flex items-center gap-2">
              <CheckCircle2 size={16} className="text-emerald-600 shrink-0" />
              <span>{adminListSuccessMessage}</span>
            </div>
            <button
              type="button"
              onClick={() => setAdminListSuccessMessage(null)}
              className="text-emerald-700 hover:text-emerald-900 p-1"
            >
              <X size={14} />
            </button>
          </div>
        )}

        {/* Admins Table / Responsive List */}
        <div className="overflow-x-auto">
          <table className="w-full text-left border-collapse">
            <thead>
              <tr className="border-b border-[#E2E8F0] text-xs font-semibold text-[#475569] uppercase tracking-wider bg-[#F8FAFC]">
                <th className="py-3 px-4">Name</th>
                <th className="py-3 px-4">Email</th>
                <th className="py-3 px-4">Status</th>
                <th className="py-3 px-4">Created Date</th>
                <th className="py-3 px-4 text-right">Actions</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-[#E2E8F0] text-sm text-[#0F172A]">
              {adminsList.map((admin) => (
                <tr key={admin.id} className="hover:bg-[#F8FAFC]/80 transition-colors">
                  <td className="py-3.5 px-4 font-medium flex items-center gap-2">
                    <div className="w-8 h-8 rounded-full bg-slate-100 border border-slate-200 flex items-center justify-center text-xs font-semibold text-slate-700 shrink-0">
                      {admin.name.charAt(0).toUpperCase()}
                    </div>
                    <span className="truncate max-w-[140px] sm:max-w-none">{admin.name}</span>
                    {admin.isPrimaryAdmin && (
                      <span className="text-[11px] font-semibold text-purple-800 bg-purple-50 border border-purple-200 px-2 py-0.5 rounded-full ml-1 shrink-0">
                        Primary
                      </span>
                    )}
                    {admin.isCurrentAdmin && (
                      <span className="text-[11px] font-semibold text-emerald-800 bg-emerald-100 px-2 py-0.5 rounded-full ml-1 shrink-0">
                        You
                      </span>
                    )}
                  </td>
                  <td className="py-3.5 px-4 text-[#475569]">{admin.email}</td>
                  <td className="py-3.5 px-4">
                    <span className="inline-flex items-center gap-1.5 text-xs font-medium text-emerald-700 bg-emerald-50 border border-emerald-200 px-2.5 py-0.5 rounded-full">
                      <span className="w-1.5 h-1.5 rounded-full bg-emerald-500" />
                      Active
                    </span>
                  </td>
                  <td className="py-3.5 px-4 text-xs text-[#64748B]">
                    {admin.createdAt
                      ? new Date(admin.createdAt).toLocaleDateString(undefined, {
                          year: "numeric",
                          month: "short",
                          day: "numeric",
                        })
                      : "—"}
                  </td>
                  <td className="py-3.5 px-4 text-right">
                    {admin.isPrimaryAdmin ? (
                      <div className="flex items-center justify-end" title="The primary administrator account cannot be removed">
                        <span className="inline-flex items-center gap-1.5 px-2.5 py-1.5 rounded-lg text-xs font-normal text-[#94A3B8] bg-slate-50 border border-slate-200 cursor-not-allowed">
                          <Lock size={12} />
                          Protected
                        </span>
                      </div>
                    ) : admin.isCurrentAdmin ? (
                      <div className="flex items-center justify-end" title="You cannot remove your own administrator account">
                        <span className="inline-flex items-center gap-1.5 px-2.5 py-1.5 rounded-lg text-xs font-normal text-[#94A3B8] bg-slate-50 border border-slate-200 cursor-not-allowed">
                          <Lock size={12} />
                          Current User
                        </span>
                      </div>
                    ) : (
                      <div className="flex items-center justify-end">
                        <button
                          type="button"
                          onClick={() => handleOpenRemoveDialog(admin)}
                          className="inline-flex items-center gap-1.5 px-2.5 py-1.5 rounded-lg text-xs font-medium text-red-600 bg-red-50 hover:bg-red-100 border border-red-200 transition-colors focus:outline-none focus:ring-2 focus:ring-red-500"
                        >
                          <UserMinus size={13} />
                          Remove Admin
                        </button>
                      </div>
                    )}
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </div>

      {/* ── Modal: Add New Administrator ────────────────────────────── */}
      {isAddModalOpen && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/40 backdrop-blur-sm animate-fade-in">
          <div className="bg-white rounded-2xl border border-[#E2E8F0] shadow-xl w-full max-w-lg p-6 flex flex-col gap-5 max-h-[90vh] overflow-y-auto">
            <div className="flex items-center justify-between border-b border-[#E2E8F0] pb-4">
              <div>
                <h3 className="font-heading text-lg font-semibold text-[#0F172A]">
                  Add New Administrator
                </h3>
                <p className="text-xs text-[#64748B] mt-0.5">
                  Create a new administrator account with dashboard access.
                </p>
              </div>
              <button
                type="button"
                onClick={() => setIsAddModalOpen(false)}
                className="p-1 rounded-lg text-[#64748B] hover:text-[#0F172A] hover:bg-[#F1F5F9]"
              >
                <X size={18} />
              </button>
            </div>

            {addAdminError && (
              <div className="p-3 bg-red-50 text-red-800 border border-red-200 text-xs rounded-lg flex items-center gap-2">
                <AlertCircle size={15} className="shrink-0 text-red-600" />
                <span>{addAdminError}</span>
              </div>
            )}

            <form onSubmit={handleOpenConfirmDialog} className="flex flex-col gap-4">
              {/* Name */}
              <div className="flex flex-col gap-1.5">
                <label
                  htmlFor="newAdminName"
                  className="font-sans text-xs font-semibold text-[#45464D] uppercase tracking-wider"
                >
                  Name
                </label>
                <input
                  id="newAdminName"
                  type="text"
                  required
                  value={newAdminName}
                  onChange={(e) => setNewAdminName(e.target.value)}
                  placeholder="e.g. Rahul Menon"
                  className="w-full px-3.5 py-2.5 rounded-lg border border-[#CBD5E1] text-sm text-[#0F172A] focus:outline-none focus:ring-2 focus:ring-[#059669] focus:border-transparent transition-all"
                />
              </div>

              {/* Email */}
              <div className="flex flex-col gap-1.5">
                <label
                  htmlFor="newAdminEmail"
                  className="font-sans text-xs font-semibold text-[#45464D] uppercase tracking-wider"
                >
                  Email
                </label>
                <input
                  id="newAdminEmail"
                  type="email"
                  required
                  value={newAdminEmail}
                  onChange={(e) => setNewAdminEmail(e.target.value)}
                  placeholder="e.g. rahul@e-wakku.com"
                  className="w-full px-3.5 py-2.5 rounded-lg border border-[#CBD5E1] text-sm text-[#0F172A] focus:outline-none focus:ring-2 focus:ring-[#059669] focus:border-transparent transition-all"
                />
              </div>

              {/* Password with Generator Button */}
              <div className="flex flex-col gap-1.5">
                <div className="flex items-center justify-between">
                  <label
                    htmlFor="newAdminPassword"
                    className="font-sans text-xs font-semibold text-[#45464D] uppercase tracking-wider"
                  >
                    Password
                  </label>
                  <button
                    type="button"
                    onClick={handleGeneratePassword}
                    className="inline-flex items-center gap-1 text-xs font-medium text-[#059669] hover:text-[#047857] hover:underline"
                  >
                    <Sparkles size={13} />
                    Generate Password
                  </button>
                </div>
                <div className="relative">
                  <input
                    id="newAdminPassword"
                    type={showNewAdminPassword ? "text" : "password"}
                    required
                    value={newAdminPassword}
                    onChange={(e) => {
                      setNewAdminPassword(e.target.value);
                      setIsAutoGenerated(false);
                    }}
                    placeholder="Enter or generate password"
                    className="w-full pl-3.5 pr-10 py-2.5 rounded-lg border border-[#CBD5E1] text-sm text-[#0F172A] focus:outline-none focus:ring-2 focus:ring-[#059669] focus:border-transparent transition-all"
                  />
                  <button
                    type="button"
                    onClick={() => setShowNewAdminPassword((p) => !p)}
                    aria-label={showNewAdminPassword ? "Hide password" : "Show password"}
                    className="absolute right-3 top-1/2 -translate-y-1/2 text-[#94A3B8] hover:text-[#475569] p-1"
                  >
                    {showNewAdminPassword ? <EyeOff size={16} /> : <Eye size={16} />}
                  </button>
                </div>
                {isAutoGenerated && (
                  <span className="text-[11px] text-emerald-700 flex items-center gap-1 mt-0.5">
                    <Check size={12} /> Automatically generated cryptographically secure password.
                  </span>
                )}
              </div>

              {/* Retype Password */}
              <div className="flex flex-col gap-1.5">
                <label
                  htmlFor="newAdminConfirmPassword"
                  className="font-sans text-xs font-semibold text-[#45464D] uppercase tracking-wider"
                >
                  Retype Password
                </label>
                <div className="relative">
                  <input
                    id="newAdminConfirmPassword"
                    type={showNewAdminConfirmPassword ? "text" : "password"}
                    required
                    value={newAdminConfirmPassword}
                    onChange={(e) => setNewAdminConfirmPassword(e.target.value)}
                    placeholder="Confirm password"
                    className="w-full pl-3.5 pr-10 py-2.5 rounded-lg border border-[#CBD5E1] text-sm text-[#0F172A] focus:outline-none focus:ring-2 focus:ring-[#059669] focus:border-transparent transition-all"
                  />
                  <button
                    type="button"
                    onClick={() => setShowNewAdminConfirmPassword((p) => !p)}
                    aria-label={showNewAdminConfirmPassword ? "Hide password" : "Show password"}
                    className="absolute right-3 top-1/2 -translate-y-1/2 text-[#94A3B8] hover:text-[#475569] p-1"
                  >
                    {showNewAdminConfirmPassword ? <EyeOff size={16} /> : <Eye size={16} />}
                  </button>
                </div>
              </div>

              {/* Live Checklist */}
              <div className="bg-[#F8FAFC] border border-[#E2E8F0] rounded-lg p-3 flex flex-col gap-1.5 text-xs">
                <span className="font-semibold text-[#475569]">Password Requirements:</span>
                <ul className="grid grid-cols-1 sm:grid-cols-2 gap-1 text-[11px]">
                  {newAdminChecklist.map((rule) => {
                    let color = "text-[#64748B]";
                    let icon = <span className="w-1.5 h-1.5 rounded-full bg-[#CBD5E1] inline-block shrink-0" />;

                    if (rule.satisfied) {
                      color = "text-emerald-700 font-medium";
                      icon = <Check size={12} className="text-[#059669] shrink-0" />;
                    } else if (rule.isViolation) {
                      color = "text-red-700 font-medium";
                      icon = <X size={12} className="text-red-600 shrink-0" />;
                    }

                    return (
                      <li key={rule.id} className={`flex items-center gap-1.5 ${color}`}>
                        {icon}
                        <span>{rule.label}</span>
                      </li>
                    );
                  })}
                </ul>
              </div>

              {/* Actions */}
              <div className="flex items-center justify-end gap-2 pt-2 border-t border-[#E2E8F0]">
                <button
                  type="button"
                  onClick={() => setIsAddModalOpen(false)}
                  className="px-4 py-2 text-xs font-medium text-[#64748B] hover:text-[#0F172A] hover:bg-[#F1F5F9] rounded-lg transition-colors"
                >
                  Cancel
                </button>
                <button
                  type="submit"
                  className="inline-flex items-center justify-center gap-1.5 px-4 py-2 bg-[#059669] hover:bg-[#047857] text-white text-xs font-medium rounded-lg transition-colors shadow-sm outline-none focus-visible:ring-2 focus-visible:ring-[#059669]"
                >
                  Create Admin
                </button>
              </div>
            </form>
          </div>
        </div>
      )}

      {/* ── Dialog: Confirmation Before Creation ───────────────────── */}
      {isConfirmDialogOpen && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/40 backdrop-blur-sm animate-fade-in">
          <div className="bg-white rounded-2xl border border-[#E2E8F0] shadow-xl w-full max-w-md p-6 flex flex-col gap-4">
            <div className="w-12 h-12 rounded-full bg-emerald-50 border border-emerald-100 flex items-center justify-center text-[#059669] mx-auto">
              <ShieldCheck size={24} />
            </div>

            <div className="text-center">
              <h4 className="font-heading text-lg font-semibold text-[#0F172A]">
                Create New Administrator?
              </h4>
              <p className="font-sans text-xs sm:text-sm text-[#475569] mt-2 leading-relaxed">
                You are about to create an administrator account for{" "}
                <span className="font-semibold text-[#0F172A]">{newAdminName}</span> (
                <span className="font-semibold text-[#0F172A]">{newAdminEmail}</span>). This account
                will be granted access to the E-Wakku admin dashboard. Please confirm that the details
                are correct.
              </p>
            </div>

            <div className="flex items-center justify-end gap-2 pt-4 border-t border-[#E2E8F0]">
              <button
                type="button"
                onClick={() => setIsConfirmDialogOpen(false)}
                disabled={isCreatingAdmin}
                className="px-4 py-2 text-xs font-medium text-[#64748B] hover:text-[#0F172A] hover:bg-[#F1F5F9] rounded-lg transition-colors"
              >
                Cancel
              </button>
              <button
                type="button"
                onClick={handleConfirmCreateAdmin}
                disabled={isCreatingAdmin}
                className="inline-flex items-center justify-center gap-1.5 px-4 py-2 bg-[#059669] hover:bg-[#047857] text-white text-xs font-medium rounded-lg transition-colors shadow-sm outline-none focus-visible:ring-2 focus-visible:ring-[#059669] disabled:opacity-50"
              >
                {isCreatingAdmin ? (
                  <>
                    <Loader2 size={14} className="animate-spin" />
                    Creating...
                  </>
                ) : (
                  "Confirm & Create"
                )}
              </button>
            </div>
          </div>
        </div>
      )}

      {/* ── Dialog: Confirmation Before Removal ───────────────────── */}
      {isRemoveDialogOpen && (
        <div
          className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/40 backdrop-blur-sm animate-fade-in"
          role="dialog"
          aria-modal="true"
          aria-labelledby="remove-admin-dialog-title"
        >
          <div className="bg-white rounded-2xl border border-[#E2E8F0] shadow-xl w-full max-w-md p-6 flex flex-col gap-4">
            <div className="w-12 h-12 rounded-full bg-red-50 border border-red-100 flex items-center justify-center text-red-600 mx-auto">
              <UserMinus size={24} />
            </div>

            <div className="text-center">
              <h4 id="remove-admin-dialog-title" className="font-heading text-lg font-semibold text-[#0F172A]">
                Remove Administrator?
              </h4>
              <p className="font-sans text-xs sm:text-sm text-[#475569] mt-2 leading-relaxed">
                Are you sure you want to remove{" "}
                <span className="font-semibold text-[#0F172A]">{adminToRemove?.name}</span> (
                <span className="font-semibold text-[#0F172A]">{adminToRemove?.email}</span>) from E-Wakku administrator access? This action will revoke their administrative privileges. They may lose access to the dashboard immediately.
              </p>
              <div className="mt-3 p-2.5 bg-amber-50 border border-amber-200 rounded-lg text-left">
                <p className="text-xs text-amber-800 flex items-start gap-1.5 leading-relaxed">
                  <AlertTriangle size={14} className="text-amber-600 shrink-0 mt-0.5" />
                  <span>This action cannot be undone from this screen. Make sure you have selected the correct administrator.</span>
                </p>
              </div>
            </div>

            {removeAdminError && (
              <div className="p-3 bg-red-50 text-red-800 border border-red-200 text-xs rounded-lg flex items-center gap-2">
                <AlertCircle size={15} className="shrink-0 text-red-600" />
                <span>{removeAdminError}</span>
              </div>
            )}

            <div className="flex items-center justify-end gap-2 pt-4 border-t border-[#E2E8F0]">
              <button
                type="button"
                onClick={handleCloseRemoveDialog}
                disabled={isRemovingAdmin}
                className="px-4 py-2 text-xs font-medium text-[#64748B] hover:text-[#0F172A] hover:bg-[#F1F5F9] rounded-lg transition-colors"
              >
                Cancel
              </button>
              <button
                type="button"
                onClick={handleConfirmRemoveAdmin}
                disabled={isRemovingAdmin}
                className="inline-flex items-center justify-center gap-1.5 px-4 py-2 bg-red-600 hover:bg-red-700 text-white text-xs font-medium rounded-lg transition-colors shadow-sm outline-none focus-visible:ring-2 focus-visible:ring-red-600 disabled:opacity-50"
              >
                {isRemovingAdmin ? (
                  <>
                    <Loader2 size={14} className="animate-spin" />
                    Removing...
                  </>
                ) : (
                  "Remove Admin"
                )}
              </button>
            </div>
          </div>
        </div>
      )}

      {/* ── Dialog: Credential-Sharing Message (Section 12) ────────── */}
      {createdAdminCredentials && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/50 backdrop-blur-sm animate-fade-in">
          <div className="bg-white rounded-2xl border border-[#E2E8F0] shadow-2xl w-full max-w-lg p-6 flex flex-col gap-5">
            <div className="flex items-center gap-3 border-b border-[#E2E8F0] pb-4">
              <div className="w-10 h-10 rounded-full bg-emerald-100 text-emerald-700 flex items-center justify-center shrink-0">
                <ShieldCheck size={22} />
              </div>
              <div>
                <h3 className="font-heading text-lg font-semibold text-[#0F172A]">
                  Administrator Created Successfully
                </h3>
                <p className="text-xs text-[#64748B]">
                  Temporary credentials generated for initial sign-in.
                </p>
              </div>
            </div>

            <div className="text-xs sm:text-sm text-[#334155] leading-relaxed flex flex-col gap-2">
              <p>Hello <span className="font-semibold text-[#0F172A]">{createdAdminCredentials.name}</span>,</p>
              <p>Your administrator account for E-Wakku has been created successfully.</p>
              <p className="text-[#64748B]">
                Below are the login credentials. Copy this message and share it directly and privately with the intended administrator only.
              </p>
            </div>

            {/* Credential Card */}
            <div className="p-4 rounded-xl bg-[#F8FAFC] border border-[#CBD5E1] flex flex-col gap-2 font-mono text-xs">
              <div className="flex items-center justify-between">
                <span className="text-[#64748B] font-sans text-xs">Login Email:</span>
                <span className="font-semibold text-[#0F172A] select-all">
                  {createdAdminCredentials.email}
                </span>
              </div>
              <div className="flex items-center justify-between">
                <span className="text-[#64748B] font-sans text-xs">Temporary Password:</span>
                <span className="font-semibold text-[#059669] select-all tracking-wide">
                  {createdAdminCredentials.password}
                </span>
              </div>
            </div>

            {/* Prominent Security Notice */}
            <div className="p-3.5 bg-amber-50 border border-amber-200 rounded-xl flex items-start gap-2.5 text-xs text-amber-900 leading-normal">
              <ShieldAlert size={18} className="text-amber-700 shrink-0 mt-0.5" />
              <div>
                <span className="font-semibold">Security Notice: </span>
                These credentials are confidential. Share them only with the actual administrator through a private communication channel. Do not share them publicly, in public groups, or on social media. Do not forward this message to anyone else.
              </div>
            </div>

            {/* Dialog Action Buttons */}
            <div className="flex items-center justify-end gap-2.5 pt-2 border-t border-[#E2E8F0]">
              <button
                type="button"
                onClick={handleCopyCredentials}
                className="inline-flex items-center justify-center gap-1.5 px-4 py-2 bg-[#F1F5F9] hover:bg-[#E2E8F0] text-[#0F172A] text-xs font-semibold rounded-lg transition-colors border border-[#CBD5E1] shadow-sm outline-none focus-visible:ring-2 focus-visible:ring-[#059669]"
              >
                {isCopied ? (
                  <>
                    <Check size={14} className="text-emerald-600" />
                    Copied to Clipboard!
                  </>
                ) : (
                  <>
                    <Copy size={14} />
                    Copy Credentials
                  </>
                )}
              </button>
              <button
                type="button"
                onClick={handleCloseCredentialsDialog}
                className="inline-flex items-center justify-center px-5 py-2 bg-[#059669] hover:bg-[#047857] text-white text-xs font-semibold rounded-lg transition-colors shadow-sm outline-none focus-visible:ring-2 focus-visible:ring-[#059669]"
              >
                Done
              </button>
            </div>
          </div>
        </div>
      )}
    </div>
  );
}
